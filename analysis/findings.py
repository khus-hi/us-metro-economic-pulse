"""Turn the analysis outputs into findings. Every number in findings.md is
computed here from the data; none is typed by hand."""
from __future__ import annotations

import pandas as pd


def _table(df: pd.DataFrame, fmt: dict[str, str] | None = None) -> str:
    fmt = fmt or {}
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if pd.isna(v):
                cells.append("n/a")
            elif c in fmt:
                cells.append(format(v, fmt[c]))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def build(pulse: pd.DataFrame, cv: pd.DataFrame, now: pd.DataFrame, coefs: dict,
          pay: pd.DataFrame, dim: pd.DataFrame, cfg: dict, pulse_cfg: dict) -> tuple[str, dict]:
    names = dim.set_index("cbsa_code")["short_name"].str.strip()
    n_acc = pulse_cfg.get("acceleration_months", 3)
    top = cfg.get("top_n", 5)
    counts = pulse.dropna(subset=["pulse"]).groupby("month_date").size()
    latest = counts.index.max()
    L = pulse[pulse["month_date"] == latest].copy()
    L["metro"] = L["cbsa_code"].map(names)
    out, facts = [], {"latest_month": f"{latest:%Y-%m}"}

    out.append(f"# Metro pulse findings, data through {latest:%B %Y}\n")
    out.append("Generated by `python -m analysis run` from the mart CSVs in `dashboard/data/`. "
               f"Weights: {pulse_cfg['weights']}. Openings source: {pulse_cfg.get('openings_source')}.")
    if pulse_cfg.get("openings_source") == "jolts_state":
        om = L["openings_month"].max()
        out.append(f"State JOLTS openings were last published for {om:%B %Y}" if pd.notna(om)
                   else "No JOLTS openings within the age limit, so that component is not in the latest index.")
        facts["openings_month"] = None if pd.isna(om) else f"{om:%Y-%m}"
    out.append("")

    # 1. Accelerating metros
    chg = f"pulse_change_{n_acc}m"
    acc = L.dropna(subset=[chg]).sort_values(chg, ascending=False).head(top)
    t = acc[["metro", "pulse", f"pulse_{n_acc}m_ago", chg, "nonfarm_jobs_yoy_pct", f"job_growth_{n_acc}m_ago"]]
    t.columns = ["Metro", "Pulse now", f"Pulse {n_acc}m ago", "Change", "Job growth now %", f"Job growth {n_acc}m ago %"]
    out += [f"## 1. Accelerating metros (biggest pulse gain over {n_acc} months)\n",
            _table(t, {c: ".2f" for c in t.columns[1:]}), ""]
    facts["accelerating"] = t.to_dict("records")

    # 2. Leaders and laggards
    comp_cols = ["nonfarm_jobs_yoy_pct", "unemployment_change_yoy_pp", "real_wage_growth_pp", "openings"]
    lead = L.dropna(subset=["pulse"]).sort_values("pulse", ascending=False)
    t = pd.concat([lead.head(3), lead.tail(3)])[["metro", "pulse", "pulse_rank", *comp_cols]]
    t.columns = ["Metro", "Pulse", "Rank", "Job growth %", "Unemp. change pp", "Real wage growth pp", "Openings rate"]
    out += [f"## 2. Strongest and weakest pulse, {latest:%B %Y}\n",
            _table(t, {"Pulse": ".2f", "Rank": ".0f", "Job growth %": ".2f", "Unemp. change pp": ".1f",
                       "Real wage growth pp": ".2f", "Openings rate": ".1f"}), ""]
    facts["leaders_laggards"] = t.to_dict("records")

    # 3. Analyst pay after cost of living
    soc = cfg.get("pay_soc", "15-2051")
    p = pay[pay["soc_code"] == soc].copy()
    p["metro"] = p["cbsa_code"].map(names)
    if "median_wage_cost_adjusted" in p and p["median_wage_cost_adjusted"].notna().any():
        p = p.dropna(subset=["median_wage_cost_adjusted"])
        p["nominal_rank"] = p["annual_median_wage"].rank(ascending=False, method="min")
        p["adjusted_rank"] = p["median_wage_cost_adjusted"].rank(ascending=False, method="min")
        best = p.sort_values("median_wage_cost_adjusted", ascending=False).head(top)
        t = best[["metro", "annual_median_wage", "rpp", "rpp_geo_level", "rpp_year",
                  "median_wage_cost_adjusted", "nominal_rank", "adjusted_rank"]]
        t.columns = ["Metro", "Median wage $", "RPP", "RPP level", "RPP year", "Cost-adjusted $", "Nominal rank", "Adjusted rank"]
        title = p["occupation_title"].iloc[0]
        p["rank_shift"] = p["nominal_rank"] - p["adjusted_rank"]
        mover_up = p.sort_values("rank_shift", ascending=False).iloc[0]
        mover_dn = p.sort_values("rank_shift").iloc[0]
        out += [f"## 3. Where {title} (SOC {soc}) pay goes furthest\n",
                f"OEWS May {int(p['oews_year'].iloc[0])} median annual wage divided by BEA Regional Price Parity "
                f"(US = 100). {len(p)} metros have a published median.\n",
                _table(t, {"Median wage $": ",.0f", "RPP": ".1f", "RPP year": ".0f",
                           "Cost-adjusted $": ",.0f", "Nominal rank": ".0f", "Adjusted rank": ".0f"}), "",
                f"Biggest climb after adjusting: {mover_up['metro']} (#{mover_up['nominal_rank']:.0f} -> "
                f"#{mover_up['adjusted_rank']:.0f}). Biggest drop: {mover_dn['metro']} "
                f"(#{mover_dn['nominal_rank']:.0f} -> #{mover_dn['adjusted_rank']:.0f}).", ""]
        facts["analyst_pay"] = t.to_dict("records")
        facts["pay_movers"] = {"up": [mover_up["metro"], mover_up["nominal_rank"], mover_up["adjusted_rank"]],
                               "down": [mover_dn["metro"], mover_dn["nominal_rank"], mover_dn["adjusted_rank"]]}
    else:
        out += ["## 3. Analyst pay after cost of living\n",
                "Not available yet: the marts have no Regional Price Parity column. Re-run ingest (bea) and dbt.", ""]

    # 4. Boston (focus) vs peers
    focus, peers = cfg["focus_metro"], cfg["peers"]
    grp = L[L["cbsa_code"].isin([focus, *peers])].copy()
    grp = grp.merge(pay[pay["soc_code"] == soc][["cbsa_code", *(["median_wage_cost_adjusted"]
                    if "median_wage_cost_adjusted" in pay else [])]], on="cbsa_code", how="left")
    cols = ["metro", "pulse", "pulse_rank", "nonfarm_jobs_yoy_pct", "unemployment_rate",
            "unemployment_change_yoy_pp", "real_wage_growth_pp"]
    if "median_wage_cost_adjusted" in grp:
        cols.append("median_wage_cost_adjusted")
    t = grp.sort_values("pulse", ascending=False)[cols]
    t.columns = ["Metro", "Pulse", "Rank of 50", "Job growth %", "Unemp. rate %", "Unemp. change pp",
                 "Real wage growth pp", *(["Data sci. pay, cost-adj. $"] if len(cols) == 8 else [])]
    fname = names.get(focus, focus)
    better = {"Pulse": False, "Job growth %": False, "Unemp. rate %": True, "Unemp. change pp": True,
              "Real wage growth pp": False, "Data sci. pay, cost-adj. $": False}
    ranks = []
    for c, asc in better.items():
        if c in t:
            r = t[c].rank(ascending=asc, method="min")[t["Metro"] == fname]
            if len(r) and pd.notna(r.iloc[0]):
                ranks.append(f"{c}: #{r.iloc[0]:.0f} of {t[c].notna().sum()}")
    out += [f"## 4. {fname} vs peers, {latest:%B %Y}\n",
            _table(t, {"Pulse": ".2f", "Rank of 50": ".0f", "Job growth %": ".2f", "Unemp. rate %": ".1f",
                       "Unemp. change pp": ".1f", "Real wage growth pp": ".2f", "Data sci. pay, cost-adj. $": ",.0f"}),
            "", f"{fname}'s place in this group: " + "; ".join(ranks) + ".", ""]
    facts["peers"] = t.to_dict("records")
    facts["focus_ranks"] = ranks

    # 5. Nowcast
    o = cv[cv["fold"] == "all folds"].iloc[0]
    now = now.copy()
    now["metro"] = now["cbsa_code"].map(names)
    rise = now.sort_values("nowcast_yoy_pp", ascending=False).head(top)
    t = rise[["metro", "latest_rate", "same_month_last_year", "nowcast", "nowcast_yoy_pp"]]
    tm = now["target_month"].max()
    imputed = bool(now["uses_imputed_lag"].any())
    ago = f"{tm - pd.DateOffset(years=1):%b %Y} rate %" + (" (interpolated)" if imputed else "")
    t.columns = ["Metro", f"{now['latest_month'].max():%b %Y} rate %", ago, f"{tm:%b %Y} nowcast %", "Nowcast vs year ago pp"]
    out += [f"## 5. Unemployment nowcast for {tm:%B %Y}\n",
            f"Time-series CV over {int(o['test_rows'])} one-month-ahead forecasts ({len(cv) - 1} yearly folds):\n",
            _table(cv, {c: ".2f" for c in cv.columns if c.startswith(("mape", "mae"))} | {"train_rows": ".0f"}), "",
            f"Overall MAPE: model {o['mape_model']:.2f}%, seasonal naive {o['mape_seasonal_naive']:.2f}%, "
            f"last-value naive {o['mape_naive_last']:.2f}%.\n",
            "Largest expected year-over-year rises:\n",
            _table(t, {c: ".2f" for c in t.columns[1:]}), ""]
    if imputed:
        out.append("Note: BLS published no October 2025 metro rates (shutdown); the year-ago value for this nowcast "
                   "is interpolated from Sep and Nov 2025.\n")
    out.append("Ridge coefficients (per unit of each feature): " +
               ", ".join(f"{k} {v:+.3f}" for k, v in coefs.items()) + "\n")
    facts["nowcast_cv"] = o.to_dict()
    facts["nowcast_rises"] = t.to_dict("records")
    return "\n".join(out), facts
